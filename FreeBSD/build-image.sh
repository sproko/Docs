#!/bin/sh
# Build the deploy USB image: a copy of the stock FreeBSD memstick image with
# our /etc/installerconfig added, which makes the installer run the deploy
# questions instead of the normal menus, plus an offline package repo so the
# install needs no network.
#
# The stock stick already carries base as an offline pkgbase repo
# (/usr/freebsd-packages/offline). This adds a second one beside it, "deploy",
# holding packages.txt and all Wi-Fi + GPU firmware, so any box's hardware
# works from first boot.
#
# Runs on FreeBSD 15 amd64, as root, with internet (to fetch the packages). The
# memstick's root filesystem is UFS, which Linux can't reliably write.
#
#   ./make-secrets.sh                        # once, writes secrets.conf
#   ./build-image.sh FreeBSD-15.1-RELEASE-amd64-memstick.img
#   dd if=build/FreeBSD-15.1-RELEASE-amd64-deploy.img of=/dev/daX bs=1m conv=sync status=progress

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
BUILD_DIR="$SCRIPT_DIR/build"

SRC_IMG="${1:-}"
if [ -z "$SRC_IMG" ] || [ ! -f "$SRC_IMG" ]; then
    echo "Usage: $0 <FreeBSD-*-memstick.img> [output.img]" >&2
    exit 1
fi
OUT_IMG="${2:-$BUILD_DIR/$(basename "$SRC_IMG" | sed 's/-memstick\.img$//')-deploy.img}"

[ "$(uname -s)" = "FreeBSD" ] || { echo "Run this on FreeBSD (the image is UFS)." >&2; exit 1; }
[ "$(id -u)" -eq 0 ] || { echo "Run as root (needs mdconfig and mount)." >&2; exit 1; }
[ -f "$SCRIPT_DIR/secrets.conf" ] || { echo "No secrets.conf: run ./make-secrets.sh first." >&2; exit 1; }
# Packages are fetched for this host's ABI, so it must match the image's
case "$(pkg config ABI)" in
    FreeBSD:15:amd64) ;;
    *) echo "Build on FreeBSD 15 amd64 (this is $(pkg config ABI))." >&2; exit 1 ;;
esac

# ============================================================================
# Assemble installerconfig
# ============================================================================
# One file in two halves (see installer/preamble.sh): settings + questions
# above the "#!", then the chrooted setup with everything it installs inlined,
# since the chroot can't see the USB stick.
mkdir -p "$BUILD_DIR"
CONFIG="$BUILD_DIR/installerconfig"

# Writes a here-doc that recreates $2 at path $1 inside the new system
embed_file() {
    if grep -q '^__DEPLOY_EOF__$' "$2"; then
        echo "$2 contains the here-doc delimiter" >&2; exit 1
    fi
    echo "mkdir -p '$(dirname "$1")'"
    echo "cat > '$1' <<'__DEPLOY_EOF__'"
    cat "$2"
    echo "__DEPLOY_EOF__"
    echo "chmod $3 '$1'"
}

umask 077
{
    echo "# Generated by build-image.sh on $(date '+%Y-%m-%d %H:%M'). Contains password hashes."
    cat "$SCRIPT_DIR/deploy.conf"
    cat "$SCRIPT_DIR/installer/preamble.sh"

    echo "#!/bin/sh"
    cat "$SCRIPT_DIR/deploy.conf"
    cat "$SCRIPT_DIR/secrets.conf"
    embed_file /usr/local/sbin/deploy-provision         "$SCRIPT_DIR/provision.sh"               755
    embed_file /usr/local/etc/deploy.conf               "$SCRIPT_DIR/deploy.conf"                644
    embed_file /usr/local/etc/deploy-packages.txt       "$SCRIPT_DIR/packages.txt"               644
    embed_file /usr/local/etc/rc.d/deploy_firstboot     "$SCRIPT_DIR/firstboot/deploy_firstboot" 755
    cat "$SCRIPT_DIR/installer/setup.sh"
} > "$CONFIG"

# Catch syntax errors here rather than halfway through an install
awk '/^#!/{exit} {print}' "$CONFIG" | sh -n
awk '/^#!/{b=1} b' "$CONFIG" | sh -n
echo "Assembled $CONFIG"

# ============================================================================
# Fetch the offline "deploy" repo
# ============================================================================
# Firmware comes from the kmods repo, built for this exact minor release.
REPO="$BUILD_DIR/deploy-repo"
rm -rf "$REPO"
mkdir -p "$REPO"
export ASSUME_ALWAYS_YES=yes
pkg update
# shellcheck disable=SC2046
pkg fetch -d -o "$REPO" -r FreeBSD-ports $(grep -vE '^[[:space:]]*(#|$)' "$SCRIPT_DIR/packages.txt")
# shellcheck disable=SC2046
pkg fetch -d -o "$REPO" -r FreeBSD-ports-kmods \
    $(pkg rquery -g -r FreeBSD-ports-kmods %n 'wifi-firmware-*' 'gpu-firmware-*')
pkg repo "$REPO"
REPO_MB="$(du -sm "$REPO" | cut -f1)"
echo "Deploy repo: $(find "$REPO" -name '*.pkg' | wc -l | tr -d ' ') packages, ${REPO_MB} MB"

# ============================================================================
# Write it all into a copy of the memstick image
# ============================================================================
echo "Copying $SRC_IMG -> $OUT_IMG"
cp "$SRC_IMG" "$OUT_IMG"
chmod 600 "$OUT_IMG"
# The stock root filesystem is sized to its contents, so make room for the
# repo (plus slack for UFS overhead) before attaching.
truncate -s "+$((REPO_MB + REPO_MB / 4 + 128))M" "$OUT_IMG"

MNT="$(mktemp -d)"
MD="$(mdconfig -a -t vnode -f "$OUT_IMG")"
cleanup() {
    umount "$MNT" 2>/dev/null || true
    mdconfig -d -u "$MD" 2>/dev/null || true
    rmdir "$MNT" 2>/dev/null || true
}
trap cleanup EXIT INT TERM

# Stock layout: MBR with the ESP as s1 and the root UFS as s2 (labelled
# FreeBSD_Install), with or without a BSD label "a" inside s2. Grow each layer
# into the space added above.
gpart recover "$MD" >/dev/null 2>&1 || true
gpart resize -i 2 "$MD"
if [ -e "/dev/${MD}s2a" ]; then
    gpart resize -i 1 "${MD}s2"
    ROOT_DEV="/dev/${MD}s2a"
elif [ -e "/dev/${MD}s2" ]; then
    ROOT_DEV="/dev/${MD}s2"
else
    { echo "Unexpected layout on $SRC_IMG:"; gpart show -r "$MD"; } >&2
    exit 1
fi
growfs -y "$ROOT_DEV"

mount "$ROOT_DEV" "$MNT"
[ -x "$MNT/usr/sbin/bsdinstall" ] || { echo "$ROOT_DEV doesn't look like the installer root" >&2; exit 1; }
[ -f "$MNT/usr/freebsd-packages/repos/FreeBSD-base-offline.conf" ] \
    || { echo "No offline base repo on $SRC_IMG; use a 15.x memstick image." >&2; exit 1; }
install -m 600 "$CONFIG" "$MNT/etc/installerconfig"
echo "Installed /etc/installerconfig on $ROOT_DEV"
rm -rf "$MNT/usr/freebsd-packages/deploy"
cp -R "$REPO" "$MNT/usr/freebsd-packages/deploy"
echo "Installed the deploy repo at /usr/freebsd-packages/deploy"
df -h "$MNT"

cleanup
trap - EXIT INT TERM

# Run via sudo, hand the output back so it can be scp'd off; modes stay 600
if [ -n "${SUDO_USER:-}" ]; then
    chown -R "$SUDO_USER" "$BUILD_DIR"
fi

echo
echo "Built $OUT_IMG"
echo "Write it to a stick (check the device first: this erases it):"
echo "  FreeBSD: dd if=$OUT_IMG of=/dev/daX bs=1m conv=sync status=progress"
echo "  Linux:   sudo dd if=$OUT_IMG of=/dev/sdX bs=1M conv=fsync status=progress"
