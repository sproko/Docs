#!/bin/sh
# Write secrets.conf: the standard root and user password hashes, plus the SSH
# public keys to authorize, for build-iso.sh to bake into the installer.
# POSIX sh + openssl.
#
#   ./make-secrets.sh                      # authorizes ~/.ssh/id_ed25519.pub
#   ./make-secrets.sh key1.pub key2.pub    # authorizes these instead
#
# secrets.conf is gitignored: this repo is public, and a SHA-512 crypt hash of a
# shared password is still crackable offline, so it stays off GitHub.

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
OUT="$SCRIPT_DIR/secrets.conf"

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

[ $# -eq 0 ] && set -- "$HOME/.ssh/id_ed25519.pub"
for key in "$@"; do
    [ -f "$key" ] || { echo "No such key file: $key" >&2; exit 1; }
done

trap 'stty echo 2>/dev/null' EXIT INT TERM

# Prompts twice, then prints the SHA-512 crypt hash ($6$...) that the Debian
# installer's preseed and chpasswd -e take.
hash_password() {
    while :; do
        printf '%s password: ' "$1" >&2
        stty -echo; read -r pw1; stty echo; echo >&2
        printf 'Again: ' >&2
        stty -echo; read -r pw2; stty echo; echo >&2
        if [ -z "$pw1" ]; then
            echo "Empty password, try again." >&2
        elif [ "$pw1" != "$pw2" ]; then
            echo "Passwords don't match, try again." >&2
        else
            break
        fi
    done
    printf '%s\n' "$pw1" | openssl passwd -6 -stdin
}

. "$SCRIPT_DIR/deploy.conf"

ROOT_PW_HASH="$(hash_password root)"
USER_PW_HASH="$(hash_password "$DEPLOY_USER")"

umask 077
{
    echo "# Generated by make-secrets.sh on $(date '+%Y-%m-%d'). Do not commit."
    echo "ROOT_PW_HASH='$ROOT_PW_HASH'"
    echo "USER_PW_HASH='$USER_PW_HASH'"
    echo "AUTHORIZED_KEYS='$(cat "$@")'"
} > "$OUT"

echo "Wrote $OUT"
echo "  root + $DEPLOY_USER password hashes"
echo "  $(cat "$@" | grep -c .) SSH key(s) from: $*"
